/** Текст справки: собираем таблицу сценария в HTML. */
function scenarioHelpHtml() {
  let html = '';
  SCENARIO.stages.forEach(function (st) {
    html += '<h3>Этап ' + st.num + '. ' + st.title + '</h3>';
    html += '<table><tr><th style="width:14%">ЗАДАНИЕ</th><th style="width:26%">ДЕЙСТВИЯ</th>' +
            '<th style="width:26%">ТРЕБОВАНИЯ</th><th style="width:20%">ФИАСКО</th><th style="width:14%">КОММЕНТАРИЙ</th></tr>';
    st.tasks.forEach(function (t) {
      html += '<tr><td>' + t.title + '</td><td>' + t.action + '</td><td>' + t.requirement + '</td>' +
              '<td class="fia">' + t.fiasko + '</td><td class="com">' + t.comment + '</td></tr>';
    });
    html += '</table>';
  });
  return html;
}

/** Быстрый доступ к задаче сценария по номеру этапа и id. */
function scenarioTask(stageNum, id) {
  const st = SCENARIO.stages.filter(function (s) { return s.num === stageNum; })[0];
  if (!st) return null;
  return st.tasks.filter(function (t) { return t.id === id; })[0] || null;
}
